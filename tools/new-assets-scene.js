// Writes docs/scenes/New Assets.md: every 🔴 and 🟡 docs asset (not Text) in rows, 🔴 first, by
// type then name, each spaced by its shapes' size. Assets with no shapes (Pfx, Tx, Sound, ...)
// are 1 m labeled boxes, all 15 m above the sea. Rerun after Asset or Shape lines change; it owns
// the file.
//   node tools/new-assets-scene.js
const fs = require('fs');
const path = require('path');
const Shapes = require('./shapes');
const Mesh = require('./shape-mesh');
const Config = require('./config');

const DOCS = path.join(__dirname, '..', '..', 'docs');
const OUT = path.join(DOCS, 'scenes', 'New Assets.md');
// Widths of Unity prefabs that shapes "use", in meters (rough; only for spacing).
const PREFAB_SIZE = { AirBubble: 0.2, RuinRoundThin: 3.8, BlackJar1: 0.8 };
const ROW = 24; // a row wraps past this many meters
const GAP = 1.5;
const Y = Config.load(null).environment.seaLevel + 15; // the rows stand 15 m above the sea

const docs = Shapes.readDocs(DOCS);

// [x, z] half extents of an asset's shapes, following "use".
function extent(name, trail = []) {
  let x = 0.5, z = 0.5;
  for (const s of docs.shapes[name] || []) {
    let ex, ez;
    if (s.kind === 'use') {
      const sc = s.scale || [1, 1, 1];
      [ex, ez] = docs.shapes[s.name] && !trail.includes(s.name) ? extent(s.name, [...trail, name])
        : [(PREFAB_SIZE[s.name] || 1) / 2, (PREFAB_SIZE[s.name] || 1) / 2];
      ex = ex * sc[0] + Math.abs(s.at[0]);
      ez = ez * sc[2] + Math.abs(s.at[2]);
    } else {
      const pts = Mesh.triangles(s).flatMap(t => t.p);
      ex = Math.max(...pts.map(p => Math.abs(p[0])));
      ez = Math.max(...pts.map(p => Math.abs(p[2])));
    }
    x = Math.max(x, ex);
    z = Math.max(z, ez);
  }
  return [x, z];
}

const list = Object.entries(docs.assets).filter(([, a]) => a.chip !== '🟢' && a.type !== 'Text')
  .sort(([n1, a], [n2, b]) => (a.chip === '🔴' ? 0 : 1) - (b.chip === '🔴' ? 0 : 1) || (a.type || '').localeCompare(b.type || '') || n1.localeCompare(n2));
const lines = [];
let x = 0, z = 0, depth = 0, chip = null;
const f = v => +v.toFixed(2) || 0;
for (const [name, a] of list) {
  const [ex, ez] = extent(name);
  if (chip !== null && a.chip !== chip) { z += depth + GAP * 3; x = 0; depth = 0; } // 🟡 starts a new block
  else if (x > 0 && x + 2 * ex > ROW) { z += depth + GAP; x = 0; depth = 0; }
  chip = a.chip;
  lines.push(`- Piece: ${name} | ${f(x + ex)} ${Y} ${f(z + ez)} | 0 0 0 | 1`);
  x += 2 * ex + GAP;
  depth = Math.max(depth, 2 * ez);
}
const red = list.filter(([, a]) => a.chip === '🔴').length;
fs.writeFileSync(OUT, `---
name: New Assets
type: scene
---
# Scene

Every 🔴 and 🟡 asset in the docs (${red} 🔴 in the front rows, ${list.length - red} 🟡 behind), by type then name; ones with no shapes yet are labeled boxes. Generated by \`node tools/new-assets-scene.js\` in layout; rerun it rather than editing here.

${lines.join('\n')}
`);
console.log(`${list.length} assets (${red} red) -> ${OUT}`);
